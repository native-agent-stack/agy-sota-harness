#!/usr/bin/env python3
"""Generate and verify docs/adr/CATALOG.md & SOTA_ECOSYSTEM_MANIFEST.json ADR parity (MADR 4.0 + GitHub Evidence)."""

from __future__ import annotations

import argparse
import datetime as dt
import json
import pathlib
import re
from typing import Any

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
ADR_DIR = REPO_ROOT / "docs" / "adr"
CATALOG_PATH = ADR_DIR / "CATALOG.md"
MANIFEST_PATH = REPO_ROOT / "SOTA_ECOSYSTEM_MANIFEST.json"
REVISIT_DAYS = 45

REQUIRED_META = (
    "Status",
    "Date",
    "Layer",
    "Evidence Grade",
    "GitHub Evidence",
    "Revisit Trigger",
)
REQUIRED_SECTIONS = (
    "## Context and Problem Statement",
    "## Decision Outcome",
    "## Alternatives Considered",
    "## Verification Witness",
)
GITHUB_URL_RE = re.compile(r"https://github\.com/[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+")


def parse_adr(path: pathlib.Path) -> dict[str, Any]:
    text = path.read_text(encoding="utf-8")
    title_match = re.search(r"^#\s+(ADR-\d{4}):\s+(.+)$", text, re.MULTILINE)
    if not title_match:
        raise ValueError(f"{path.name}: missing '# ADR-XXXX: Title' heading")

    adr_id = title_match.group(1)
    if not path.name.startswith(f"{adr_id}-"):
        raise ValueError(f"{path.name}: heading ID '{adr_id}' does not match filename prefix")

    meta: dict[str, Any] = {
        "id": adr_id,
        "title": title_match.group(2).strip(),
        "file": path.name,
    }
    for key in REQUIRED_META:
        m = re.search(rf"^-\s+\*\*{re.escape(key)}:\*\*\s+(.+)$", text, re.MULTILINE)
        if not m:
            raise ValueError(f"{path.name}: missing metadata field '**{key}:**'")
        meta[key] = m.group(1).strip()

    gh_urls = sorted(set(GITHUB_URL_RE.findall(str(meta["GitHub Evidence"]))))
    if not gh_urls:
        raise ValueError(f"{path.name}: '**GitHub Evidence:**' must cite >=1 https://github.com/<owner>/<repo> URL")
    meta["githubUrls"] = gh_urls

    for sec in REQUIRED_SECTIONS:
        if sec not in text:
            raise ValueError(f"{path.name}: missing required section '{sec}'")

    dt.date.fromisoformat(str(meta["Date"]))
    return meta


def load_and_validate_adrs(adr_dir: pathlib.Path = ADR_DIR) -> list[dict[str, Any]]:
    adr_files = sorted(adr_dir.glob("ADR-[0-9][0-9][0-9][0-9]-*.md"))
    if len(adr_files) < 14:
        raise ValueError(f"Expected >= 14 ADRs in {adr_dir}, found {len(adr_files)}")

    rows = [parse_adr(p) for p in adr_files]
    seen_ids: set[str] = set()
    for idx, r in enumerate(rows, start=1):
        expected_id = f"ADR-{idx:04d}"
        if r["id"] in seen_ids:
            raise ValueError(f"Duplicate ADR identifier '{r['id']}' in {r['file']}")
        if r["id"] != expected_id:
            raise ValueError(f"Non-sequential ADR numbering: expected '{expected_id}', found '{r['id']}' ({r['file']})")
        seen_ids.add(r["id"])
    return rows


def render_catalog(rows: list[dict[str, Any]]) -> str:
    as_of = max(dt.date.fromisoformat(str(r["Date"])) for r in rows)
    due = [str(r["id"]) for r in rows if (as_of - dt.date.fromisoformat(str(r["Date"]))).days > REVISIT_DAYS]
    lines = [
        "# AGY Full-Landscape SOTA Architecture Decision Catalog (`L0–L12` × `T0–T8` × `P0–P5`)",
        "",
        "<!-- GENERATED by scripts/architecture_catalog.py; do not edit by hand. -->",
        "",
        f"- **ADR Count:** {len(rows)} Accepted",
        "- **Format:** MADR 4.0 with Mandatory GitHub Primary-Source Evidence",
        f"- **Revisit Threshold:** {REVISIT_DAYS} days",
        f"- **Due for Revisit:** {', '.join(due) if due else 'None'}",
        "",
        "| ADR | Layer | Title | Status | Date | Grade | GitHub Primary Evidence | Revisit Trigger |",
        "| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |",
    ]
    for r in rows:
        gh_links = ", ".join(f"[{u.split('github.com/', 1)[1]}]({u})" for u in r["githubUrls"][:3])
        if len(r["githubUrls"]) > 3:
            gh_links += f" (+{len(r['githubUrls']) - 3})"
        lines.append(
            f"| [{r['id']}]({r['file']}) | {r['Layer']} | {r['title']} | {r['Status']} | {r['Date']} | "
            f"{r['Evidence Grade']} | {gh_links} | {r['Revisit Trigger']} |"
        )
    lines.append("")
    return "\n".join(lines)


def build_manifest_adr_block(rows: list[dict[str, Any]]) -> dict[str, Any]:
    return {
        "format": "MADR-4.0-GitHub-Evidenced",
        "catalogPath": "docs/adr/CATALOG.md",
        "generatorScript": "scripts/architecture_catalog.py",
        "revisitThresholdDays": REVISIT_DAYS,
        "adrCount": len(rows),
        "records": [
            {
                "id": r["id"],
                "layer": r["Layer"],
                "title": r["title"],
                "status": r["Status"],
                "date": r["Date"],
                "evidenceGrade": r["Evidence Grade"],
                "file": f"docs/adr/{r['file']}",
                "githubUrls": r["githubUrls"],
            }
            for r in rows
        ],
    }


def main() -> int:
    parser = argparse.ArgumentParser(description="Build or check docs/adr/CATALOG.md & manifest ADR parity")
    parser.add_argument(
        "--check", action="store_true", help="Verify CATALOG.md and manifest ADR parity without writing"
    )
    parser.add_argument(
        "--sync-manifest", action="store_true", help="Update adrGovernance inside SOTA_ECOSYSTEM_MANIFEST.json"
    )
    args = parser.parse_args()

    rows = load_and_validate_adrs(ADR_DIR)
    rendered = render_catalog(rows)
    expected_block = build_manifest_adr_block(rows)

    if args.check:
        if not CATALOG_PATH.is_file():
            raise SystemExit("CATALOG.md missing; run scripts/architecture_catalog.py")
        if CATALOG_PATH.read_text(encoding="utf-8") != rendered:
            raise SystemExit("CATALOG.md is out of sync with docs/adr/ADR-*.md")
        if not MANIFEST_PATH.is_file():
            raise SystemExit("SOTA_ECOSYSTEM_MANIFEST.json missing")
        manifest_data = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
        if manifest_data.get("adrGovernance") != expected_block:
            raise SystemExit("SOTA_ECOSYSTEM_MANIFEST.json adrGovernance is out of sync with docs/adr/ADR-*.md")
        print(f"ADR catalog & manifest verified: {len(rows)} GitHub-evidenced ADRs valid, 0 drift.")
        return 0

    CATALOG_PATH.write_text(rendered, encoding="utf-8")
    if args.sync_manifest and MANIFEST_PATH.is_file():
        manifest_data = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
        manifest_data["adrGovernance"] = expected_block
        MANIFEST_PATH.write_text(json.dumps(manifest_data, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {CATALOG_PATH.relative_to(REPO_ROOT)} ({len(rows)} ADRs).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
